"""Generate the pages of francisca.cr with a shared header and footer.

The English pages (index, research, talks, pubs, thesis, 404) and the Spanish
homepage (espanol) are written from this script, so the header, navigation,
social links and footer only need changing in one place.

To change a page: edit its text below, then run from the repository root

    python3 _tools/build.py

and commit both this script and the regenerated .html files. Editing the .html
files directly also works, but those edits are overwritten the next time this
script runs.

Shared styles live in style.css. When you change style.css, bump STYLE_VERSION
so browsers fetch the new file instead of a cached copy.

The blog (blog.md, _posts/, _layouts/, tag/) is built by Jekyll and is not
touched by this script. Folders starting with "_" are not published, so this
file never appears on the site.
"""
